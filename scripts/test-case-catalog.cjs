// Human-readable scenarios mapped to specific executable assertions. Unmapped cases stay NOT RUN.
const groups = [];
function group(name, rows) {
  groups.push({
    name,
    cases: rows.map((r, i) => ({
      id: `${name.split(' ')[0]}-${String(i + 1).padStart(2, '0')}`,
      scenario: r[0],
      preconditions: r[1],
      steps: r[2],
      expected: r[3],
      evidence: r[4] || null,
    })),
  });
}
